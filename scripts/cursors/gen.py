COLORS = {"#": BODY, "v": VIOLET, "w": WHITE}


def render(name, hotspot, art):
    rows = [r for r in art.strip("\n").split("\n")]
    rows = [r.rstrip() for r in rows]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch in COLORS:
                px[x, y] = COLORS[ch]
    # auto white outline: transparent pixels 8-adjacent to body/violet pixels
    src = img.copy().load()
    for y in range(16):
        for x in range(16):
            if src[x, y][3] == 0:
                near = False
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        nx, ny = x + dx, y + dy
                        if 0 <= nx < 16 and 0 <= ny < 16 and src[nx, ny][3] != 0 and src[nx, ny] != WHITE:
                            near = True
                if near:
                    px[x, y] = WHITE
    big = img.resize((32, 32), Image.NEAREST)
    big.save(f"{OUT}/{name}.png")
    hx, hy = hotspot[0] * 2 + 1, hotspot[1] * 2 + 1
    return big, (hx, hy)


def main():
    order = list(A.keys())
    rendered = {}
    for name in order:
        hs, art = A[name]
        rendered[name] = render(name, hs, art)

    # contact sheet: 6x zoom on site-void background with labels
    Z, PAD, CELL = 6, 14, 32 * 6 + 28
    cols = 4
    import math
    rws = math.ceil(len(order) / cols)
    sheet = Image.new("RGBA", (cols * CELL + PAD, rws * CELL + PAD), BG)
    d = ImageDraw.Draw(sheet)
    for i, name in enumerate(order):
        img, (hx, hy) = rendered[name]
        cx = PAD + (i % cols) * CELL
        cy = PAD + (i // cols) * CELL
        zoom = img.resize((32 * Z, 32 * Z), Image.NEAREST)
        sheet.alpha_composite(zoom, (cx, cy))
        # hotspot marker
        d.rectangle([cx + hx * Z, cy + hy * Z, cx + hx * Z + Z - 1, cy + hy * Z + Z - 1], outline=(240, 101, 94, 255), width=2)
        d.text((cx, cy + 32 * Z + 4), f"{name}  hot=({hx},{hy})", fill=(154, 161, 169, 255))
    sheet.save(f"{OUT}/sheet.png")

    # emit data URIs + hotspots
    with open(f"{OUT}/uris.txt", "w") as f:
        for name in order:
            img, (hx, hy) = rendered[name]
            buf = io.BytesIO()
            img.save(buf, format="PNG", optimize=True)
            b64 = base64.b64encode(buf.getvalue()).decode()
            f.write(f"{name} {hx} {hy} data:image/png;base64,{b64}\n")
    print("done:", ", ".join(order))


main()
